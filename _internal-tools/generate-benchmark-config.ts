#!/usr/bin/env -S deno run --allow-read --allow-write

import { toFileUrl } from '@std/path'
import type { BenchmarkCase, BenchmarkConfig } from '../benchmarks/config.ts'
import { configs as existingConfigs } from '../benchmarks/config.ts'

type WorkspaceCases = Map<string, BenchmarkCase>

const ROOT = Deno.cwd()
const TARGET_FILE = `${ROOT}/benchmarks/config.ts`
const WORKSPACES = ['array', 'date', 'function', 'math', 'object', 'text']

function getWorkspaceConfigMap(): Map<string, WorkspaceCases> {
  const workspaceMap = new Map<string, WorkspaceCases>()

  for (const config of existingConfigs) {
    const byName = new Map<string, BenchmarkCase>()
    for (const benchCase of config.cases) {
      byName.set(benchCase.name, benchCase)
    }
    workspaceMap.set(config.workspace, byName)
  }

  return workspaceMap
}

async function getExportFiles(workspace: string): Promise<string[]> {
  const modPath = `${ROOT}/${workspace}/mod.ts`
  const content = await Deno.readTextFile(modPath)
  const matches = content.matchAll(/export\s+\*\s+from\s+'(\.\/[^']+\.ts)'/g)

  const files: string[] = []
  for (const match of matches) {
    files.push(match[1])
  }

  return files
}

async function discoverRuntimeExports(
  workspace: string,
): Promise<Array<{ name: string; importPath: string }>> {
  const exportFiles = await getExportFiles(workspace)
  const discovered: Array<{ name: string; importPath: string }> = []
  const seen = new Set<string>()

  for (const importPath of exportFiles) {
    const absolute = `${ROOT}/${workspace}/${importPath.replace('./', '')}`
    const moduleUrl = toFileUrl(absolute).href
    const moduleExports = await import(moduleUrl)

    for (const [name, value] of Object.entries(moduleExports)) {
      if (typeof value !== 'function') continue
      if (seen.has(name)) continue

      seen.add(name)
      discovered.push({ name, importPath })
    }
  }

  return discovered
}

function buildCase(
  workspace: string,
  discovered: { name: string; importPath: string },
  existingByWorkspace: Map<string, WorkspaceCases>,
): BenchmarkCase {
  const existing = existingByWorkspace.get(workspace)?.get(discovered.name)

  return {
    name: discovered.name,
    canonicalName: existing?.canonicalName,
    fixtureSize: existing?.fixtureSize ?? 'medium',
    importPath: discovered.importPath,
    args: existing?.args,
  }
}

function renderCase(case_: BenchmarkCase): string {
  const fields: string[] = [
    `name: '${case_.name}'`,
  ]

  if (case_.canonicalName) {
    fields.push(`canonicalName: '${case_.canonicalName}'`)
  }

  fields.push(`fixtureSize: '${case_.fixtureSize}'`)
  fields.push(`importPath: '${case_.importPath}'`)

  if (case_.args) {
    fields.push(`args: ${case_.args.toString()}`)
  }

  return `      { ${fields.join(', ')} },`
}

function renderConfig(configs: BenchmarkConfig[]): string {
  const sections = configs
    .map((config) => {
      const cases = config.cases.map(renderCase).join('\n')

      return [
        '  {',
        `    workspace: '${config.workspace}',`,
        '    cases: [',
        cases,
        '    ],',
        '  },',
      ].join('\n')
    })
    .join('\n')

  return [
    '/**',
    ' * Benchmark configuration - defines which functions to benchmark per workspace.',
    ' *',
    ' * This file is generated by _internal-tools/generate-benchmark-config.ts.',
    ' * Existing case metadata (fixtureSize, canonicalName, args) is preserved when possible.',
    ' */',
    '',
    'export interface BenchmarkConfig {',
    '  workspace: string',
    '  cases: BenchmarkCase[]',
    '}',
    '',
    'export interface BenchmarkCase {',
    '  name: string',
    "  fixtureSize: 'small' | 'medium' | 'large'",
    '  importPath: string',
    '  canonicalName?: string',
    '  args?: () => unknown[]',
    '}',
    '',
    'export const configs: BenchmarkConfig[] = [',
    sections,
    ']',
    '',
  ].join('\n')
}

async function main(): Promise<void> {
  const existingByWorkspace = getWorkspaceConfigMap()
  const nextConfigs: BenchmarkConfig[] = []

  for (const workspace of WORKSPACES) {
    const discovered = await discoverRuntimeExports(workspace)
    const cases = discovered.map((runtimeExport) =>
      buildCase(workspace, runtimeExport, existingByWorkspace)
    )

    nextConfigs.push({
      workspace,
      cases,
    })
  }

  await Deno.writeTextFile(TARGET_FILE, renderConfig(nextConfigs))
  globalThis.console.log(`Generated ${TARGET_FILE}`)
}

if (import.meta.main) {
  await main()
}
